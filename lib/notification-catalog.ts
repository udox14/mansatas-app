export type NotificationChannel = 'fcm' | 'webpush' | 'in_app'

export type NotificationTargetKind =
  | 'staff_role'
  | 'staff_all'
  | 'staff_users'
  | 'parent_student'
  | 'parent_students'
  | 'parent_class'
  | 'parent_grade'
  | 'parents_all'

export type NotificationTargetConfig = {
  kind: NotificationTargetKind
  value?: string | number | null
  ids?: string[]
}

export type NotificationReminderConfig = {
  enabled: boolean
  delayMinutes?: number
  leadMinutes: number
  frequencyMinutes: number
  daysBefore?: number
  windowStart?: string
  windowEnd?: string
}

export type NotificationEventDefinition = {
  key: string
  label: string
  description: string
  group: 'keuangan' | 'orang_tua' | 'kesiswaan' | 'akademik' | 'agenda' | 'administrasi'
  defaultEnabled: boolean
  defaultTitle: string
  defaultBody: string
  defaultUrl: string
  defaultChannels: NotificationChannel[]
  defaultTarget: NotificationTargetConfig
  defaultLevel: 'info' | 'warning' | 'critical'
  placeholders: string[]
  reminder: NotificationReminderConfig
}

